-- Bobik Run 1.9.0: XP levels, public level leaderboard, individual run history,
-- achievements metadata sync and a shared rotating global hunt.
-- Apply once in Supabase Dashboard -> SQL Editor after the earlier 1.8.x migrations.

-- Nightmare is a first-class leaderboard mode (0 Normal, 1 Three Lives,
-- 2 Hardcore, 3 Nightmare).
do $$
declare c record;
begin
  for c in
    select conname from pg_constraint
    where conrelid = 'public.leaderboard'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%mode%'
  loop
    execute format('alter table public.leaderboard drop constraint %I', c.conname);
  end loop;
end $$;
alter table public.leaderboard
  add constraint leaderboard_mode_0_3_check check (mode between 0 and 3);

-- Five best runs are selected from the full run history for each profile/mode/difficulty.
create table if not exists public.run_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mode smallint not null check (mode between 0 and 3),
  difficulty smallint not null check (difficulty between 0 and 2),
  distance integer not null check (distance between 0 and 100000000),
  created_at timestamptz not null default now()
);
create index if not exists run_history_profile_idx
  on public.run_history(user_id, mode, difficulty, distance desc, created_at desc);

-- Public progression row; only the authenticated owner can update it through the RPC.
create table if not exists public.player_progress (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Игрок',
  xp bigint not null default 0 check (xp >= 0),
  level integer not null default 1 check (level between 1 and 1000),
  achievements text[] not null default '{}',
  updated_at timestamptz not null default now()
);
create index if not exists player_progress_rank_idx
  on public.player_progress(level desc, xp desc, updated_at asc);

alter table public.run_history enable row level security;
alter table public.player_progress enable row level security;
revoke all on public.run_history, public.player_progress from anon, authenticated;
grant select on public.run_history, public.player_progress to anon, authenticated;
drop policy if exists "run_history_public_read" on public.run_history;
create policy "run_history_public_read" on public.run_history
  for select to anon, authenticated using (true);
drop policy if exists "player_progress_public_read" on public.player_progress;
create policy "player_progress_public_read" on public.player_progress
  for select to anon, authenticated using (true);

-- The client passes its total XP; the database derives the corresponding level using
-- the same progression curve as progression.js (120 + 8 * level^1.28 XP per level).
create or replace function public.sync_bobik_progress(
  p_total_xp bigint,
  p_achievements text[] default '{}'
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_name text;
  v_xp bigint := greatest(0, least(coalesce(p_total_xp, 0), 24366487));
  v_level integer := 1;
  v_threshold bigint := 0;
  v_need bigint;
  v_achievements text[] := coalesce(p_achievements, '{}');
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED'; end if;
  select username into v_name from public.profiles where id = v_uid;
  if v_name is null then v_name := 'Игрок'; end if;
  -- Keep achievements bounded and avoid null array values.
  v_achievements := coalesce(v_achievements, '{}');
  if cardinality(v_achievements) > 100 then
    v_achievements := v_achievements[1:100];
  end if;
  while v_level < 1000 loop
    v_need := floor(120 + 8 * power(v_level::numeric, 1.28))::bigint;
    exit when v_threshold + v_need > v_xp;
    v_threshold := v_threshold + v_need;
    v_level := v_level + 1;
  end loop;
  insert into public.player_progress(user_id, display_name, xp, level, achievements, updated_at)
  values (v_uid, v_name, v_xp, v_level, v_achievements, now())
  on conflict (user_id) do update set
    display_name = excluded.display_name,
    xp = greatest(public.player_progress.xp, excluded.xp),
    level = greatest(public.player_progress.level, excluded.level),
    achievements = excluded.achievements,
    updated_at = now();
  return jsonb_build_object('xp', v_xp, 'level', v_level, 'achievements', to_jsonb(v_achievements));
end;
$$;
revoke all on function public.sync_bobik_progress(bigint, text[]) from public, anon;
grant execute on function public.sync_bobik_progress(bigint, text[]) to authenticated;

-- Save every completed run and keep the existing best-score leaderboard in sync.
create or replace function public.record_bobik_run(
  p_mode integer,
  p_difficulty integer,
  p_distance integer
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_name text;
  v_best integer;
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_mode not between 0 and 3 or p_difficulty not between 0 and 2 then
    raise exception 'INVALID_CATEGORY';
  end if;
  if p_distance is null or p_distance < 0 or p_distance > 100000000 then
    raise exception 'INVALID_SCORE';
  end if;
  select username into v_name from public.profiles where id = v_uid;
  v_name := coalesce(v_name, 'Игрок');
  insert into public.run_history(user_id, mode, difficulty, distance)
  values (v_uid, p_mode, p_difficulty, p_distance);
  insert into public.leaderboard(user_id, mode, difficulty, display_name, best_distance, updated_at)
  values (v_uid, p_mode, p_difficulty, v_name, p_distance, now())
  on conflict (user_id, mode, difficulty) do update set
    display_name = excluded.display_name,
    best_distance = greatest(public.leaderboard.best_distance, excluded.best_distance),
    updated_at = now();
  select best_distance into v_best from public.leaderboard
  where user_id = v_uid and mode = p_mode and difficulty = p_difficulty;
  return jsonb_build_object('saved', true, 'best_distance', v_best);
end;
$$;
revoke all on function public.record_bobik_run(integer, integer, integer) from public, anon;
grant execute on function public.record_bobik_run(integer, integer, integer) to authenticated;

