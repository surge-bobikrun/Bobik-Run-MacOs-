-- One active worldwide hunt. The target remains the same until somebody clears it.
create table if not exists public.bobik_global_hunt_state (
  id smallint primary key check (id = 1),
  hunt_id uuid not null,
  title text not null default 'Глобальная дистанция',
  target_distance integer not null check (target_distance between 1000 and 50000),
  difficulty smallint not null default 1 check (difficulty between 0 and 2),
  created_at timestamptz not null default now()
);
insert into public.bobik_global_hunt_state(id, hunt_id, title, target_distance, difficulty)
values (1, gen_random_uuid(), 'Первая глобальная охота', 6000, 2)
on conflict (id) do nothing;

create table if not exists public.bobik_hunt_records (
  id bigint generated by default as identity primary key,
  hunt_id uuid not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null default 'Игрок',
  target_distance integer not null,
  actual_distance integer not null,
  created_at timestamptz not null default now()
);
create index if not exists bobik_hunt_records_user_idx
  on public.bobik_hunt_records(user_id, created_at desc);
alter table public.bobik_global_hunt_state enable row level security;
alter table public.bobik_hunt_records enable row level security;
revoke all on public.bobik_global_hunt_state, public.bobik_hunt_records from anon, authenticated;
grant select on public.bobik_global_hunt_state to anon, authenticated;
drop policy if exists "bobik_hunt_state_public_read" on public.bobik_global_hunt_state;
create policy "bobik_hunt_state_public_read" on public.bobik_global_hunt_state
  for select to anon, authenticated using (true);

create or replace function public.finish_bobik_hunt(p_hunt_id uuid, p_distance integer)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_name text;
  v_state public.bobik_global_hunt_state%rowtype;
  v_next_id uuid := gen_random_uuid();
  v_targets integer[] := array[3000, 4000, 5000, 6000, 7500, 9000, 11000, 13000, 15000];
  v_target integer;
  v_reward integer;
  v_difficulty integer;
begin
  if v_uid is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_distance is null or p_distance < 0 or p_distance > 100000000 then
    raise exception 'INVALID_SCORE';
  end if;
  select * into v_state from public.bobik_global_hunt_state where id = 1 for update;
  if not found then raise exception 'HUNT_NOT_INITIALIZED'; end if;
  if v_state.hunt_id <> p_hunt_id then
    return jsonb_build_object('success', false, 'already_completed', true,
      'hunt', jsonb_build_object('hunt_id', v_state.hunt_id, 'title', v_state.title,
        'target_distance', v_state.target_distance, 'difficulty', v_state.difficulty));
  end if;
  if p_distance < v_state.target_distance then
    return jsonb_build_object('success', false, 'not_enough', true,
      'remaining', v_state.target_distance - p_distance);
  end if;
  select username into v_name from public.profiles where id = v_uid;
  insert into public.bobik_hunt_records(hunt_id, user_id, display_name, target_distance, actual_distance)
  values (v_state.hunt_id, v_uid, coalesce(v_name, 'Игрок'), v_state.target_distance, p_distance);
  v_reward := 900 + floor(v_state.target_distance / 10.0)::integer;
  v_target := v_targets[1 + floor(random() * array_length(v_targets, 1))::integer];
  v_difficulty := case when v_target >= 9000 then 2 when v_target >= 6000 then 1 else 0 end;
  update public.bobik_global_hunt_state
  set hunt_id = v_next_id,
      title = 'Глобальная дистанция',
      target_distance = v_target,
      difficulty = v_difficulty,
      created_at = now()
  where id = 1;
  return jsonb_build_object('success', true, 'reward_xp', v_reward,
    'completed_target', v_state.target_distance,
    'hunt', jsonb_build_object('hunt_id', v_next_id, 'title', 'Глобальная дистанция',
      'target_distance', v_target, 'difficulty', v_difficulty));
end;
$$;
revoke all on function public.finish_bobik_hunt(uuid, integer) from public, anon;
grant execute on function public.finish_bobik_hunt(uuid, integer) to authenticated;

-- Leaderboard counts how many world hunts each player has won.
create or replace function public.get_bobik_hunt_leaderboard()
returns table(user_id uuid, display_name text, hunts_completed bigint,
              total_hunt_meters bigint, best_target integer, last_completed_at timestamptz)
language sql
security definer
set search_path = ''
as $$
  select r.user_id, r.display_name, count(*)::bigint,
         sum(r.target_distance)::bigint, max(r.target_distance), max(r.created_at)
  from public.bobik_hunt_records r
  group by r.user_id, r.display_name
  order by count(*) desc, sum(r.target_distance) desc, max(r.created_at) asc
  limit 50;
$$;
revoke all on function public.get_bobik_hunt_leaderboard() from public, anon;
grant execute on function public.get_bobik_hunt_leaderboard() to anon, authenticated;

